export function inferFlagCode(name: string, explicit?: string): string {
  if (explicit && FLAGS[explicit]) return explicit;
  const s = String(name || '');
  if (/新加坡|狮城|🇸🇬|\bsg\b|singapore/i.test(s)) return 'sg';
  if (/香港|🇭🇰|\bhk\b|hong\s*kong/i.test(s)) return 'hk';
  if (/日本|东京|大阪|🇯🇵|\bjp\b|japan|tokyo|osaka/i.test(s)) return 'jp';
  if (/美国|洛杉矶|硅谷|西雅图|纽约|🇺🇸|\bus\b|usa|united states/i.test(s)) return 'us';
  if (/德国|法兰克福|🇩🇪|\bde\b|germany|frankfurt/i.test(s)) return 'de';
  if (/韩国|首尔|🇰🇷|\bkr\b|korea|seoul/i.test(s)) return 'kr';
  if (/英国|伦敦|🇬🇧|\buk\b|\bgb\b|london|britain/i.test(s)) return 'gb';
  if (/台湾|台北|🇹🇼|\btw\b|taiwan/i.test(s)) return 'tw';
  if (/法国|巴黎|🇫🇷|\bfr\b|france|paris/i.test(s)) return 'fr';
  if (/荷兰|阿姆斯特丹|🇳🇱|\bnl\b|netherlands/i.test(s)) return 'nl';
  if (/加拿大|多伦多|温哥华|🇨🇦|\bca\b|canada/i.test(s)) return 'ca';
  if (/澳洲|澳大利亚|悉尼|🇦🇺|\bau\b|australia|sydney/i.test(s)) return 'au';
  return 'globe';
}

export function flagSvg(name: string, explicit?: string): string {
  return FLAGS[inferFlagCode(name, explicit)] || FLAGS.globe;
}

