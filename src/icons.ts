const TONES = ['blue', 'cyan', 'purple', 'green', 'orange', 'indigo', 'gray'] as const;

export function toneForName(name: string): string {
  let hash = 0;
  for (let i = 0; i < name.length; i++) hash = (hash * 31 + name.charCodeAt(i)) | 0;
  return TONES[Math.abs(hash) % TONES.length];
}

export function renderProgramIcon(icon?: string | null, name = '', fallbackTone?: string, fallbackGlyph?: string): string {
  if (icon && icon.startsWith('data:image/')) {
    return `<span class="app-native-icon"><img src="${icon.replace(/"/g, '&quot;')}" alt=""></span>`;
  }
  const tone = fallbackTone || toneForName(name || 'app');
  if (fallbackGlyph) {
    return `<span class="sq md ${tone}"><svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-linecap="round" stroke-linejoin="round">${fallbackGlyph}</svg></span>`;
  }
  const letter = (name.trim().slice(0, 1) || 'A').toUpperCase();
  return `<span class="sq md ${tone}" style="font-weight:700;font-size:var(--type-label)">${letter.replace(/[<>&]/g, '')}</span>`;
}

